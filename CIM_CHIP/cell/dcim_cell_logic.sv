`timescale 1ns/1ps

// One-bit digital-CIM storage and NOR-compute cell.
//
// The presentation places the input NAND in the shared Input Control block.
// Therefore this cell receives the already generated active-low cim_input_b
// and implements the per-cell NOR with the complementary SRAM node QB.  A row
// slice may fan one cim_input_b signal out to several cells without duplicating
// the input-control gate.
module dcim_cell_logic (
    input  logic clk,
    input  logic rst_n,

    // SRAM and nonvolatile controls
    input  logic write_en,
    input  logic write_data,
    
    input  logic nv_store,
    input  logic nv_recall,
    input  logic pd_en,

    // Active-low compute input generated by the row/input-control NAND:
    // cim_input_b = ~(cim_en & cim_row & activation_bit)
    input  logic cim_input_b,

    // Observable SRAM nodes for the later read/sense path
    output logic read_q,
    output logic read_qb,

    // One-cell multiplication result
    output logic cim_product
);

    fesram_cell_model u_fesram_cell_model (
        .clk        (clk),
        .rst_n      (rst_n),
        .write_en   (write_en),
        .write_data (write_data),
        .nv_store   (nv_store),
        .nv_recall  (nv_recall),
        .pd_en      (pd_en),
        .q          (read_q),
        .qb         (read_qb)
    );

    // Per-cell NOR compute gate:
    //   product = NOR(IN_b, QB)
    //           = cim_en & cim_row & activation_bit & Q
    // A disabled row drives cim_input_b high, so the NOR output becomes zero.
    // This is also the FPGA-safe binary abstraction of the silicon tri-state
    // output: inactive cells contribute zero to the following adder tree.
    assign cim_product = ~(cim_input_b | read_qb);

endmodule
