"""Generate deterministic board ROM; golden uses magnitude division, not RTL shifts."""
from pathlib import Path
import re

root = Path(__file__).resolve().parent
source = (root / '../../rtl/datapath/kws_pot_shift_rom.sv').resolve().read_text()
entries = re.findall(r"8'd(\d+): shift_amount=5'd(\d+)", source)
assert len(entries) == 76
rows = []
shifts = {int(a): int(k) for a, k in entries}
def quant(a, k, relu):
    d = 1 << k
    q, r = divmod(abs(a), d)
    q += int(2*r > d or (2*r == d and q % 2 == 1))
    q = -q if a < 0 else q
    out = max(0, min(255, q+128))
    return max(128, out) if relu else out

def append(a, addr, relu=0, last=0, error=0, mode=0, first=0,
           width=0, height=0, channels=0, tail_valid=0, tail_data=0,
           tail_channel=0, tail_y=0, tail_x=0, tail_done=0, cls=0):
    values = [(a & 0xffffffff,32),(addr>>5,3),(addr&31,5),
              (relu,1),(last,1),(error,1),(quant(a,shifts[addr],relu),8),
              (mode,2),(first,1),(width,8),(height,8),(channels,5),
              (tail_valid,1),(tail_data,8),(tail_channel,5),(tail_y,7),(tail_x,7),(tail_done,1),(cls,3)]
    assert sum(bits for _, bits in values) == 107
    payload=0
    for value,bits in values:
        assert 0 <= value < (1 << bits)
        payload=(payload<<bits)|value
    rows.append(f"            11'd{len(rows)}: data = 107'h{payload:027x};")

for addr, shift in entries:
    addr, shift = int(addr), int(shift)
    d = 1 << shift
    samples = [0, d//2, 3*d//2, -3*d//2, 2**31-1, -2**31, -7*d, 19*d+d//4]
    for j, a in enumerate(samples):
        relu = int(j == 6)
        last = int(j == 7)
        error = int(j == 7)  # Verify upstream error flag propagation.
        append(a, addr, relu, last, error)

# Real model widths and capacity boundary; short frames keep test-ROM size bounded.
pool_outputs=0
for layer,w,h,nc in [(0,61,3,2),(1,28,3,2),(2,12,4,2),(0,126,3,1)]:
    pixels={}
    for c in range(nc):
        for y in range(h):
            for x in range(w):
                addr=layer*32+c
                a=((x*17+y*29+c*43)%281-140)*(1<<shifts[addr])
                pixels[c,y,x]=quant(a,shifts[addr],1)
                valid=int(y%2==1 and x%2==1)
                golden=max(pixels[c,y-dy,x-dx] for dy in [0,1] for dx in [0,1]) if valid else 0
                done=int(valid and c==nc-1 and y==2*(h//2)-1 and x==2*(w//2)-1)
                append(a,addr,1,int(c==nc-1 and y==h-1 and x==w-1),mode=1,
                       first=int(c==0 and y==0 and x==0),width=w,height=h,channels=nc,
                       tail_valid=valid,tail_data=golden,tail_channel=c if valid else 0,
                       tail_y=y//2 if valid else 0,tail_x=x//2 if valid else 0,tail_done=done)
                pool_outputs+=valid
# FC2 UINT8 values are on the same output scale; ties choose the first class.
for values in [[128]*8,[130,210,140,210,110,150,180,160],list(range(120,128)),[255,0,1,2,3,4,5,6]]:
    cls=values.index(max(values))
    for c,q in enumerate(values):
        append((q-128)*64,128+c,last=int(c==7),mode=2,first=int(c==0),
               tail_valid=int(c==7),tail_data=max(values) if c==7 else 0,cls=cls if c==7 else 0)
assert len(rows)==1648 and pool_outputs==175
text = '''// Generated by generate_vectors.py. Golden outputs fixed at generation time.
module postprocess_vectors(input wire [10:0] index, output logic [106:0] data);
    always_comb begin
        case(index)
'''+ '\n'.join(rows)+'''
            default: data = '0;
        endcase
    end
endmodule
'''
(root / 'postprocess_vectors.sv').write_text(text)
print(f'Generated {len(rows)} golden transactions')
