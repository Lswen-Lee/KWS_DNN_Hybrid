"""Generate deterministic board ROM; golden uses magnitude division, not RTL shifts."""
from pathlib import Path
import re

root = Path(__file__).resolve().parent
source = (root / '../../rtl/datapath/kws_pot_shift_rom.sv').resolve().read_text()
entries = re.findall(r"8'd(\d+): shift_amount=5'd(\d+)", source)
assert len(entries) == 76
rows = []
for addr, shift in entries:
    addr, shift = int(addr), int(shift)
    d = 1 << shift
    samples = [0, d//2, 3*d//2, -3*d//2, 2**31-1, -2**31, -7*d, 19*d+d//4]
    for j, a in enumerate(samples):
        relu = int(j == 6)
        last = int(j == 7)
        error = int(j == 7)  # Verify upstream error flag propagation.
        q, r = divmod(abs(a), d)
        q += int(2*r > d or (2*r == d and q % 2 == 1))
        q = -q if a < 0 else q
        out = max(0, min(255, q+128))
        if relu: out = max(128, out)
        payload = a & 0xffffffff
        for value, bits in [(addr>>5,3),(addr&31,5),(relu,1),(last,1),(error,1),(out,8)]:
            payload = (payload << bits) | value
        rows.append(f"            10'd{len(rows)}: data = 51'h{payload:013x};")
text = '''// Generated by generate_vectors.py. Golden outputs fixed at generation time.
module postprocess_vectors(input wire [9:0] index, output logic [50:0] data);
    always_comb begin
        case(index)
'''+ '\n'.join(rows)+'''
            default: data = '0;
        endcase
    end
endmodule
'''
(root / 'postprocess_vectors.sv').write_text(text)
print(f'Generated {len(rows)} golden transactions')
